def get_pattern(first_category: str, second_category: str) -> dict:
    """查表获取题型范式（骨架+约束+陷阱+人味策略）

    查表逻辑：
    1. 用户命名 → 内部能力维度
    2. 在内部维度的范式表里查二级类目
    3. 命中返回该范式，未命中走该维度的默认范式（取第一个）

    返回:
        {
            "骨架": str,
            "约束": [str],
            "陷阱": str,
            "人味策略": [str] | None,
            "ability_internal": str,   # 内部维度名
            "ability_user": str,       # 用户前端命名
            "category2": str,          # 二级类目
            "is_default": bool,        # 是否走默认范式
        }
    """
    # 用户命名 → 内部维度
    internal = USER_TO_INTERNAL.get(first_category)
    if internal is None:
        # 用户填了未知的命名，回退到默认 guide（旧版兼容）
        return {
            "骨架": "请基于视频内容生成一个需要观看视频才能回答的问题。",
            "约束": ["问题应有明确答案", "不能单帧判断"],
            "陷阱": "模型可能出太宽泛或主观的问题",
            "人味策略": None,
            "ability_internal": "未知",
            "ability_user": first_category,
            "category2": second_category,
            "is_default": True,
        }

    patterns = ABILITY_PATTERNS.get(internal, {})
    if second_category in patterns:
        p = patterns[second_category]
        return {
            **p,
            "ability_internal": internal,
            "ability_user": first_category,
            "category2": second_category,
            "is_default": False,
        }
    # 未命中二级类目，走该维度的默认范式（取第一个）
    if patterns:
        default_cat2, default_p = next(iter(patterns.items()))
        return {
            **default_p,
            "ability_internal": internal,
            "ability_user": first_category,
            "category2": second_category,  # 保留用户填的二级类目名
            "is_default": True,
        }
    # 维度下没有任何范式（不应该发生）
    return {
        "骨架": "请基于视频内容生成一个需要观看视频才能回答的问题。",
        "约束": ["问题应有明确答案", "不能单帧判断"],
        "陷阱": "模型可能出太宽泛或主观的问题",
        "人味策略": None,
        "ability_internal": internal,
        "ability_user": first_category,
        "category2": second_category,
        "is_default": True,
    }


def check_difficulty_match(score: int, target_difficulty: str) -> tuple:
    """检查 6 维评分总分是否匹配目标难度档位

    返回:
        (is_match: bool, reason: str)
    """
    if target_difficulty not in DIFFICULTY_SCORE_RANGES:
        return True, ""  # 未知难度，不校验
    low, high = DIFFICULTY_SCORE_RANGES[target_difficulty]
    if low <= score <= high:
        return True, ""
    return False, f"评分{score}分不匹配目标难度'{target_difficulty}'（需{low}-{high}分）"


def check_prompt_category_match(prompt: str, first_category: str) -> tuple:
    """检查 prompt 是否与目标类目关键词有交集（旧版接口，供 validate.py 使用）

    返回:
        (is_match: bool, matched_keywords: list, total_keywords: int)
    """
    guide = get_category_guide(first_category)
    keywords = guide.get("关键词", [])
    if not keywords:
        return True, [], 0
    matched = [kw for kw in keywords if kw in prompt]
    return len(matched) > 0, matched, len(keywords)


def check_prompt_quality(prompt: str) -> list:
    """检查 prompt 质量，返回问题列表（旧版接口，供 validate.py 使用）"""
    issues = []
    if len(prompt) < 10:
        issues.append(f"prompt 过短 ({len(prompt)}字)")
    too_simple_starts = ["是不是", "有没有", "是不是有", "几个", "多少个", "什么颜色"]
    for start in too_simple_starts:
        if prompt.startswith(start) and len(prompt) < 15:
            issues.append(f"prompt 过于简单（以'{start}'开头且<15字）")
            break
    subjective_patterns = ["好不好", "美不美", "喜不喜欢", "你觉得"]
    for pat in subjective_patterns:
        if pat in prompt:
            issues.append(f"prompt 包含主观判断词（'{pat}'），难以客观评测")
            break
    return issues


