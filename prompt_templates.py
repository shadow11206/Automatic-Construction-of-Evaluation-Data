def get_category_guide(first_category: str) -> dict:
    """获取某个一级类目的引导语，未定义时返回默认值"""
    return CATEGORY_GUIDES.get(first_category, DEFAULT_GUIDE)


def check_prompt_category_match(prompt: str, first_category: str) -> tuple:
    """
    检查 prompt 是否与目标类目关键词有交集

    返回:
        (is_match: bool, matched_keywords: list, total_keywords: int)
    """
    guide = get_category_guide(first_category)
    keywords = guide.get("关键词", [])
    if not keywords:
        return True, [], 0  # 没有关键词列表则跳过检查

    matched = [kw for kw in keywords if kw in prompt]
    return len(matched) > 0, matched, len(keywords)


def build_vqa_prompt(task: dict) -> str:
    """
    根据任务信息构建发给 Qwen VL 的完整 prompt

    参数:
        task: {"一级类目": str, "二级类目": str, "目标难度": str}

    返回:
        完整的 prompt 文本
    """
    cat1 = task.get("一级类目", "")
    cat2 = task.get("二级类目", "")
    difficulty = task.get("目标难度", "中等")

    guide = get_category_guide(cat1)
    diff_desc = DIFFICULTY_DESCRIPTIONS.get(difficulty, DIFFICULTY_DESCRIPTIONS["中等"])

    return VQA_GENERATION_PROMPT.format(
        一级类目=cat1,
        二级类目=cat2,
        难度=difficulty,
        难度描述=diff_desc,
        引导语=guide["引导语"],
        反例=guide["反例"]
    )


def check_prompt_quality(prompt: str) -> list:
    """
    检查 prompt 质量，返回问题列表

    返回:
        [] 表示没有问题，非空列表表示存在质量问题
    """
    issues = []

    # 检查长度
    if len(prompt) < 10:
        issues.append(f"prompt 过短 ({len(prompt)}字)")

    # 检查是否以过于简单的方式开头
    too_simple_starts = ["是不是", "有没有", "是不是有", "几个", "多少个", "什么颜色"]
    for start in too_simple_starts:
        if prompt.startswith(start) and len(prompt) < 15:
            issues.append(f"prompt 过于简单（以'{start}'开头且<15字）")
            break

    # 检查是否包含主观判断类问题（难以评测）
    subjective_patterns = ["好不好", "美不美", "喜不喜欢", "你觉得"]
    for pat in subjective_patterns:
        if pat in prompt:
            issues.append(f"prompt 包含主观判断词（'{pat}'），难以客观评测")
            break

    return issues
