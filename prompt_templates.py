def build_vqa_prompt(task: dict) -> str:
    """根据任务信息构建发给 Qwen VL 的完整 prompt（v2 两步输出）

    参数:
        task: {"一级类目": str, "二级类目": str, "目标难度": str}

    返回:
        完整的 prompt 文本
    """
    cat1 = task.get("一级类目", "")
    cat2 = task.get("二级类目", "")
    difficulty = task.get("目标难度", "中等")

    pattern = get_pattern(cat1, cat2)

    # 人味提示：鲁棒性层强制直问，其他维度按策略推荐
    if pattern["ability_internal"] == "鲁棒性层":
        人味提示 = "\n- 人味策略：本题为鲁棒性题，必须直问，不人味（精确控制干扰项）"
    elif pattern.get("人味策略"):
        人味提示 = f"\n- 人味策略：本维度推荐 {', '.join(pattern['人味策略'])}，模型自决是否使用"
    else:
        人味提示 = "\n- 人味策略：本维度不强制人味，模型自决"

    return VQA_GENERATION_PROMPT.format(
        一级类目=cat1,
        二级类目=cat2,
        难度=difficulty,
        骨架=pattern["骨架"],
        约束="；".join(pattern["约束"]),
        陷阱=pattern["陷阱"],
        人味提示=人味提示,
    )
